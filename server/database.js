import 'dotenv/config';
import pg from 'pg';

const { Pool } = pg;

export function createPool(connectionString = process.env.DATABASE_URL) {
  if (!connectionString) throw new Error('DATABASE_URL must be set to a PostgreSQL connection string.');
  // Neon requires TLS. Keep SSL configuration in the URL because node-postgres
  // intentionally lets URL sslmode options override the separate ssl object.
  let url;
  try { url = new URL(connectionString); } catch { throw new Error('DATABASE_URL is not a valid PostgreSQL URL.'); }
  if (url.hostname.endsWith('.neon.tech') && !url.searchParams.has('sslmode')) url.searchParams.set('sslmode', 'require');
  return new Pool({ connectionString: url.toString(), max: 5, connectionTimeoutMillis: 10000, idleTimeoutMillis: 30000 });
}

export async function initializeDatabase(pool) {
  await pool.query('SELECT 1');
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
      email TEXT NOT NULL UNIQUE,
      password TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL
    );
    CREATE TABLE IF NOT EXISTS budgets (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
      month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
      year INTEGER NOT NULL CHECK (year BETWEEN 2000 AND 2100),
      created_at TIMESTAMPTZ NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL,
      UNIQUE(user_id, month, year)
    );
    CREATE TABLE IF NOT EXISTS expenses (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      title TEXT NOT NULL CHECK (char_length(title) > 0),
      category TEXT NOT NULL,
      amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
      date TIMESTAMPTZ NOT NULL,
      payment_method TEXT NOT NULL DEFAULT 'Cash',
      description TEXT NOT NULL DEFAULT '',
      transaction_type TEXT NOT NULL DEFAULT 'expense' CHECK (transaction_type = 'expense'),
      created_at TIMESTAMPTZ NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL
    );
    CREATE TABLE IF NOT EXISTS borrowed_records (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      person_name TEXT NOT NULL CHECK (char_length(person_name) > 0),
      amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
      date TIMESTAMPTZ NOT NULL,
      description TEXT NOT NULL DEFAULT '',
      repayment_status TEXT NOT NULL DEFAULT 'Pending' CHECK (repayment_status IN ('Pending','Partially Repaid','Repaid')),
      created_at TIMESTAMPTZ NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL
    );
    CREATE TABLE IF NOT EXISTS repayments (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      borrowed_record_id BIGINT NOT NULL REFERENCES borrowed_records(id) ON DELETE CASCADE,
      amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
      paid_on TIMESTAMPTZ NOT NULL,
      created_at TIMESTAMPTZ NOT NULL
    );
    CREATE INDEX IF NOT EXISTS idx_budgets_user_period ON budgets(user_id, year DESC, month DESC);
    CREATE INDEX IF NOT EXISTS idx_expenses_user_date ON expenses(user_id, date DESC, created_at DESC);
    CREATE INDEX IF NOT EXISTS idx_borrowed_user_date ON borrowed_records(user_id, date DESC);
    CREATE INDEX IF NOT EXISTS idx_repayments_record ON repayments(borrowed_record_id, paid_on);
  `);
}
